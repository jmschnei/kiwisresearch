"""Command-line interface for Kiwis Research."""

from __future__ import annotations

import asyncio
import argparse
import logging
import sys
from pathlib import Path

from .config.settings import Settings


def setup_logging(level: str = "INFO"):
    logging.basicConfig(
        level=getattr(logging, level),
        format="%(asctime)s | %(name)-20s | %(levelname)-8s | %(message)s",
        stream=sys.stdout,
    )


async def run_research(topic: str, config_path: str | None = None, iterations: int = 1, hypothesis: str = ""):
    """Run the full research pipeline for a topic, like a research job in the dashboard.

    Each iteration writes to its own folder ``<paths.output>/runs/<timestamp>-<n>/`` (paper, figures, sandbox
    files, ``state.json``) and runs generated code in the configured sandbox.
    """
    import json
    import time
    from datetime import datetime

    from .config.settings import load_settings
    from .execution.factory import make_sandbox
    from .models.usage import UsageTracker
    from .orchestrator.agent_factory import AgentFactory
    from .orchestrator.pipeline import ResearchPipeline

    settings = load_settings(config_path)
    setup_logging(settings.logging.level)
    logger = logging.getLogger("kiwis.cli")
    logger.info(f"Starting research for: {topic}")

    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    state = None
    for i in range(iterations):
        out_dir = Path(settings.paths.output) / "runs" / f"{stamp}-{i + 1}"
        out_dir.mkdir(parents=True, exist_ok=True)
        tracker = UsageTracker()
        sandbox = make_sandbox(settings, out_dir)
        factory = AgentFactory(settings, sandbox=sandbox, usage_tracker=tracker, output_dir=out_dir)
        pipeline = ResearchPipeline(settings=settings, agent_factory=factory.create, sandbox=sandbox)
        pipeline.build_default_pipeline()

        logger.info(f"Iteration {i + 1}/{iterations} -> {out_dir}")
        started = time.monotonic()
        try:
            state = await pipeline.run(topic, hypothesis)
        finally:  # keep what was produced even when a phase fails: it is what you need to debug the run
            if pipeline.state is not None:
                (out_dir / "state.json").write_text(json.dumps(pipeline.state.to_dict(), indent=2, default=str))

        logger.info(f"Iteration {i + 1} finished in {time.monotonic() - started:.0f}s, "
                    f"{tracker.total_tokens} tokens (estimated), ${tracker.total_cost:.4f}")
        paper = state.paper_draft or {}
        for label, key in (("Paper (LaTeX)", "latex_path"), ("Paper (PDF)", "pdf_path")):
            if paper.get(key):
                logger.info(f"{label}: {paper[key]}")
        if state.errors:
            logger.error("Errors encountered:")
            for err in state.errors:
                logger.error(f"  - {err}")
    return state


AGENT_TEMPLATE = '''"""{title} agent (generated by `kiwis generate`)."""

from kiwis.agents.base import AgentContext, AgentOutput, AgentState, BaseAgent


class {cls}(BaseAgent):
    ROLE = "{name}"
    DESCRIPTION = "TODO: describe what the {name} agent does."

    async def execute(self, context: AgentContext) -> AgentOutput:
        self._log_event("start", {{"topic": context.research_topic}})
        # TODO: call an LLM / tools here and return structured data for the next agents.
        return AgentOutput(agent_name=self.name, state=AgentState.COMPLETED, data={{}})
'''


def generate_agent(name: str, output_dir: Path, force: bool = False) -> Path:
    """Write a ready-to-edit ``BaseAgent`` subclass to ``<output_dir>/<name>_agent.py``."""
    import re
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", name):
        raise ValueError(f"Invalid agent name '{name}': use letters, digits and underscores, starting with a letter")
    name = name.lower()
    cls = "".join(p.capitalize() for p in name.split("_")) + "Agent"
    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / f"{name}_agent.py"
    if path.exists() and not force:
        raise FileExistsError(f"{path} already exists (use --force to overwrite)")
    path.write_text(AGENT_TEMPLATE.format(title=name.replace("_", " ").title(), cls=cls, name=name))
    return path


def init_command():
    """Entry point ``kiwis-init``: same as ``kiwis init``."""
    main(["init", *sys.argv[1:]])


def research_command():
    """Entry point ``kiwis-research``: same as ``kiwis research``."""
    main(["research", *sys.argv[1:]])


def main(argv: list[str] | None = None):
    parser = argparse.ArgumentParser(
        prog="kiwis",
        description="Multi-Agent Scientific Research Automation System",
    )
    subparsers = parser.add_subparsers(dest="command")
    
    # Init command
    init_parser = subparsers.add_parser("init", help="Initialize a new Kiwis project")
    init_parser.add_argument("project_name", nargs="?", default="kiwis-project", help="Project name")
    
    # Research command
    research_parser = subparsers.add_parser("research", help="Run the research pipeline")
    research_parser.add_argument("topic", help="Research topic")
    research_parser.add_argument("-c", "--config", help="Path to config file", default=None)
    research_parser.add_argument("-n", "--iterations", type=int, default=1, help="Number of iterations")
    research_parser.add_argument("--hypothesis", default="", help="Optional starting hypothesis")

    # Check command
    check_parser = subparsers.add_parser("check", help="Check that the configured models, sandbox and tools are ready")
    check_parser.add_argument("-c", "--config", help="Path to config file", default=None)
    check_parser.add_argument("--ping", action="store_true",
                              help="Also send a one-line prompt to each model in use (local models: loads them once)")
    
    # Serve command
    serve_parser = subparsers.add_parser("serve", help="Run the dashboard API (FastAPI)")
    serve_parser.add_argument("-c", "--config", help="Path to config file", default=None)
    serve_parser.add_argument("--host", default="127.0.0.1")
    serve_parser.add_argument("--port", type=int, default=8000)

    # Generate command
    gen_parser = subparsers.add_parser("generate", help="Scaffold a new custom agent module")
    gen_parser.add_argument("name", help="Agent name, e.g. 'statistician' (letters, digits, underscores)")
    gen_parser.add_argument("-o", "--output", help="Output directory", default=".")
    gen_parser.add_argument("--force", action="store_true", help="Overwrite an existing file")

    args = parser.parse_args(argv)
    
    if args.command == "init":
        from pathlib import Path
        project_dir = Path(args.project_name)
        project_dir.mkdir(exist_ok=True)
        
        # Create default config
        config_file = project_dir / "kiwis_config.yaml"
        config_file.write_text("""# Kiwis Research Configuration
project_name: "{name}"

pipeline:
  max_iterations: 3
  hypothesis_generation_rounds: 3
  literature_review_papers_max: 20
  peer_review_critique_rounds: 2
  auto_submit_threshold: null

sandbox:
  mode: docker  # docker | isolated
  timeout_seconds: 600
  memory_mb: 4096
  network_isolated: true
  
logging:
  level: INFO
  format: "default"
""".format(name=args.project_name))
        
        logger = logging.getLogger("kiwis.cli")
        setup_logging()
        logger.info(f"Project initialized at {project_dir}")
        logger.info(f"Config written to {config_file}")
        
    elif args.command == "research":
        state = asyncio.run(run_research(args.topic, config_path=args.config, iterations=args.iterations,
                                         hypothesis=args.hypothesis))

    elif args.command == "check":
        from .preflight import format_report, run_checks
        from .config.settings import load_settings
        results = asyncio.run(run_checks(load_settings(args.config), ping=args.ping))
        print(format_report(results))
        sys.exit(0 if all(r.ok or not r.required for r in results) else 1)
    
    elif args.command == "serve":
        try:
            import uvicorn
            from .api import create_app
        except ImportError:
            sys.exit("The API needs extra dependencies: pip install -e '.[api]'")
        from .config.settings import load_settings
        settings = load_settings(args.config)
        setup_logging(settings.logging.level)
        uvicorn.run(create_app(settings), host=args.host, port=args.port)

    elif args.command == "generate":
        setup_logging()
        try:
            path = generate_agent(args.name, Path(args.output), force=args.force)
        except (ValueError, FileExistsError) as e:
            sys.exit(str(e))
        logging.getLogger("kiwis.cli").info(f"Agent scaffold written to {path}")

    else:
        parser.print_help()


if __name__ == "__main__":
    main()
